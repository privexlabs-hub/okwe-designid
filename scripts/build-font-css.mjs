/**
 * Generates src/design-system/tokens/fonts.local.css from the downloaded font
 * manifest. Derived, never hand-typed, so the @font-face blocks cannot drift
 * from the files actually on disk.
 *
 * The upstream tokens/fonts.css is left untouched as the source of truth; this
 * file is what styles.css imports instead, so the divergence stays a readable diff.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const manifest = JSON.parse(
  await readFile(path.join(ROOT, "public/assets/fonts/fonts.manifest.json"), "utf8"),
);

const HEAD = `/* ============================================================================
   OKWE WEBFONTS — self-hosted.
   GENERATED by scripts/build-font-css.mjs from public/assets/fonts/fonts.manifest.json.
   Do not edit by hand; re-run \`npm run assets:fontcss\` instead.

   Upstream tokens/fonts.css (kept verbatim, unimported) loads these three families
   from the Google CDN. Okwe serves them locally instead: no third-party request at
   runtime, and the app works offline.

   The variable axes are the point, not an optimisation:
     Archivo       wdth 62–125    headlines are set EXPANDED (118%, covers 125%)
     Martian Mono  wdth 75–112.5  the register is set NARROW (87.5%)
   That width contrast is the identity. A static instance would silently remove it,
   so scripts/fetch-fonts.mjs refuses to write a font whose fvar axis is missing.

   Literata carries opsz 7–72 and NO width axis, so it declares font-optical-sizing
   rather than a fabricated font-stretch range.

   All three are SIL Open Font License 1.1.
   ========================================================================== */\n`;

// font-stretch on an @font-face declares the range the file covers, which the
// browser maps onto the registered wdth axis. Ranges come from the fvar table.
const face = (f) => {
  const lines = [
    `  font-family: "${f.family}";`,
    `  font-style: ${f.style};`,
    `  font-weight: ${f.weight};`,
  ];
  if (f.axes?.wdth) lines.push(`  font-stretch: ${f.axes.wdth.min}% ${f.axes.wdth.max}%;`);
  lines.push(`  font-display: swap;`);
  lines.push(`  src: url("/assets/fonts/${f.file}") format("woff2");`);
  if (f.unicodeRange) lines.push(`  unicode-range: ${f.unicodeRange};`);
  return `@font-face {\n${lines.join("\n")}\n}`;
};

const byFamily = new Map();
for (const f of manifest.fonts) {
  if (!byFamily.has(f.family)) byFamily.set(f.family, []);
  byFamily.get(f.family).push(f);
}

let out = HEAD;
for (const [family, faces] of byFamily) {
  const axes = Object.keys(faces[0].axes ?? {}).join(", ");
  out += `\n/* ---- ${family} — ${faces.length} subset${faces.length > 1 ? "s" : ""} · axes: ${axes} ---- */\n`;
  out += faces.map(face).join("\n") + "\n";
}

// Literata's optical-size axis only responds when optical sizing is enabled.
out += `
/* Literata varies its optical size with the rendered size; without this the whole
   opsz axis is inert and long-form text loses the reading-size drawing. */
:root { font-optical-sizing: auto; }
`;

const dest = path.join(ROOT, "src/design-system/tokens/fonts.local.css");
await writeFile(dest, out);
console.log(`${manifest.fonts.length} faces → ${path.relative(ROOT, dest)}`);
